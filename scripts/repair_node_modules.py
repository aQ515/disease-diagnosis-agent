"""修复 node_modules 里缺失入口文件的包（Windows 侧 npm 安装丢文件的补救）。

做法：扫描每个包的 main/exports 入口文件是否存在，缺失的包从 npmmirror
重新下载 tarball 并整体覆盖解压。跑完再扫一遍确认 0 缺失。
"""
import io
import json
import os
import sys
import tarfile
import urllib.request

ROOT = sys.argv[1] if len(sys.argv) > 1 else "node_modules"
MIRROR = "https://registry.npmmirror.com"
OUTDIR = "repaired_pkgs"


def entry_missing(pkgdir):
    """该包是否有入口文件缺失（返回缺失路径或 None）。"""
    pj = os.path.join(pkgdir, "package.json")
    if not os.path.exists(pj):
        return None
    try:
        d = json.load(open(pj, encoding="utf-8"))
    except Exception:
        return None
    main = d.get("main")
    if isinstance(main, str):
        cand = os.path.normpath(os.path.join(pkgdir, main))
        if not os.path.exists(cand):
            return main
    exp = d.get("exports")
    if isinstance(exp, dict) and "." in exp:
        v = exp["."]
        vs = [v] if isinstance(v, str) else (list(v.values()) if isinstance(v, dict) else [])
        for c in vs:
            if isinstance(c, str) and c.endswith((".js", ".cjs", ".mjs")):
                cand = os.path.normpath(os.path.join(pkgdir, c))
                if not os.path.exists(cand):
                    return c
    return None


def scan(root):
    bad = []
    for name in sorted(os.listdir(root)):
        p = os.path.join(root, name)
        if not os.path.isdir(p):
            continue
        if name.startswith("@") and os.path.isdir(p):
            for sub in sorted(os.listdir(p)):
                sp = os.path.join(p, sub)
                if entry_missing(sp):
                    bad.append((name + "/" + sub, sp))
        elif entry_missing(p):
            bad.append((name, p))
    return bad


def fetch(name, dest):
    """从镜像下载该包 tarball 并覆盖解压到 dest。"""
    pj = json.load(open(os.path.join(dest, "package.json"), encoding="utf-8"))
    ver = pj["version"]
    base = name.split("/")[-1]
    url = f"{MIRROR}/{name}/-/{base}-{ver}.tgz"
    req = urllib.request.Request(url, headers={"User-Agent": "curl/8"})
    with urllib.request.urlopen(req, timeout=120) as r:
        blob = r.read()
    os.makedirs(OUTDIR, exist_ok=True)
    safe = name.replace("/", "__")
    with open(os.path.join(OUTDIR, f"{safe}-{ver}.tgz"), "wb") as f:
        f.write(blob)
    with tarfile.open(fileobj=io.BytesIO(blob)) as t:
        for m in t.getmembers():
            if not m.name.startswith("package/"):
                continue
            m.name = os.path.relpath(m.name, "package")
            if m.name in (".", ""):
                continue
            t.extract(m, dest)
    return ver, len(blob)


bad = scan(ROOT)
print(f"缺失入口的包: {len(bad)} 个")
fixed = 0
for name, path in bad:
    try:
        ver, size = fetch(name, path)
        print(f"  [OK]   {name}@{ver}  ({size} bytes)")
        fixed += 1
    except Exception as e:  # noqa: BLE001
        print(f"  [FAIL] {name}: {e}")

print(f"\n已修复 {fixed}/{len(bad)}")
left = scan(ROOT)
print(f"复查缺失: {len(left)} 个")
for n, _ in left[:20]:
    print("  仍缺失:", n)
